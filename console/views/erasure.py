@dataclass(frozen=True)
class Section:
    """The form's subject section: the choice, each select's options (``None``: not shown) and
    why Preview is disabled ("" when it is not)."""

    choice: Choice
    kinds: list[tuple[str, str]]
    stories: Options | None
    subjects: Options | None
    scopes: list[tuple[str, str]]
    errors: Mapping[str, Sequence[str]]
    preview_disabled: str
    story_required: bool


def _subject_options(client: EngineClient, choice: Choice) -> Options | None:
    if choice.kind == "character":
        if not choice.story:
            return Options(empty="Choose a story first")
        return character_options(client, choice.story)
    if choice.kind == "catalog_character":
        return catalog_character_options(client)
    if choice.kind == "persona":
        return persona_options(client)
    return None


def build_section(
    client: EngineClient, choice: Choice, errors: Mapping[str, Sequence[str]] | None = None
) -> Section:
    """The section for ``choice``: the stories (any kind may scope to a story) and the kind's
    subjects, a pre-filled value absent from the options kept as "(not listed)"."""
    stories = subjects = None
    if choice.kind:
        stories = story_options(client).keeping(choice.story)
        found = _subject_options(client, choice)
        subjects = found.keeping(choice.subject) if found is not None else None
    disabled = subjects.empty if subjects is not None and choice.story and subjects.empty else ""
    return Section(
        choice=choice,
        kinds=list(SUBJECT_KINDS.items()),
        stories=stories,
        subjects=subjects,
        scopes=scopes_for(choice.kind) if choice.kind else [],
        errors=errors or {},
        preview_disabled=disabled,
        story_required=choice.kind == "character" or choice.scope == SCOPE_STORY,
    )


def _render_form(
    request: HttpRequest,
    client: EngineClient,
    choice: Choice,
    *,
    errors: Mapping[str, Sequence[str]] | None = None,
    engine_error: ErrorPanel | None = None,
    error_text: str = "",
) -> HttpResponse:
    context = {
        "section": build_section(client, choice, errors),
        "engine_error": engine_error,
        "error_text": error_text,
        "index_url": reverse("erasure:index"),
    }
    return render(request, "console/erasure/form.html", context)


@require_safe
def erasure_new(request: HttpRequest) -> HttpResponse:
    choice = settle(request.GET)
    client = engine_client_for(request)
    if is_htmx(request):
        context = {"section": build_section(client, choice)}
        return render(request, "console/erasure/_subject_section.html", context)
    return _render_form(request, client, choice)


def _place_error(
    request: HttpRequest,
    client: EngineClient,
    exc: EngineClientError,
    choice: Choice,
) -> HttpResponse:
    """The form again with a refusal where it belongs: a 404 at the subject (the Engine names it
    in ``details``) or the story; 422 ``invalid_erasure_scope`` at the scope; others in the
    panel, worded when the Console knows the code."""
    if isinstance(exc, EngineError) and exc.http_status == 404:
        on_subject = "subject_id" in exc.details
        name, text = ("subject", UNKNOWN_SUBJECT) if on_subject else ("story", UNKNOWN_STORY)
        return _render_form(request, client, choice, errors={name: [text]})
    if isinstance(exc, EngineError) and exc.code == SCOPE_CODE:
        return _render_form(request, client, choice, errors={"scope": [exc.message or exc.code]})
    code = exc.code if isinstance(exc, EngineError) else ""
    return _render_form(
        request, client, choice, engine_error=panel_for(exc), error_text=CODE_TEXT.get(code, "")
    )


