"""Erasure (#86): erase a subject after a dry run, with its ambiguous mentions confirmed one by one.

- ``/erasure/new/`` (GET, ``?kind=&story=&subject=&scope=``): the form. The kind and story selects
  re-render the subject section (HTMX ``hx-get``, or "Next" without JS). "Preview (dry run)" POSTs
  to the preview.
- ``/erasure/preview/`` (POST): the **dry run** (``dry_run: true``, no idempotency key), rendered in
  place (no PRG): counts, candidate mentions as unticked checkboxes, referencing stories, and the
  one way to erase: "Erase now", which carries a signed payload (:mod:`console.twostage`, kind
  ``erasure``): the subject and scope in ``body``; in ``base`` the offered candidate ids, the
  real run's idempotency key (minted now), who made it and as whom, and the dry run's answer (to
  show the preview again without a call). Also reached from "Preview again" (the same payload).
- ``/erasure/run/`` (POST only): the **real run**, only from that payload. Ticked ids outside the
  offered set, or more than 1,000, are refused with zero Engine calls. Success → PRG to the
  result; no answer → "Retry" with the same payload and ticks (the same key).
- ``/erasure/<erasure_id>/``: the result, read back from the operation log (#44; the Engine has
  none).
- ``/erasure/`` (#87): the erasure ledger (``GET /admin/erasure/status``: pending
  re-applications after a restore, the reconciler's last run), polled while a re-apply runs
  (``/erasure/status/``), "Re-apply now" (``/erasure/reconcile/``, POST), and the real runs this
  Console made, from the operation log.
- ``/erasure/boundary/`` (#87): what erasure covers and doesn't, as this Engine states it.
"""

