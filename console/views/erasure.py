@dataclass(frozen=True)
class CandidateGroup:
    table: str
    candidates: list[ErasureCandidate]


def candidate_groups(candidates: Sequence[ErasureCandidate]) -> list[CandidateGroup]:
    """The candidates by ``record_table``, groups in first-appearance order, the Engine's order
    kept within each."""
    groups: dict[str, list[ErasureCandidate]] = {}
    for candidate in candidates:
        groups.setdefault(candidate.record_table, []).append(candidate)
    return [CandidateGroup(table, items) for table, items in groups.items()]


def record_rows(records: Mapping[str, int]) -> list[tuple[str, int]]:
    """``(table, count)`` for the tables with a non-zero count, in the Engine's order."""
    return [(table, n) for table, n in records.items() if n]


def subject_link(subject: SubjectRef) -> SafeString:
    """The subject's id, linked to its Console page (a catalog character, a persona); a story
    character's id is shown as ``<code>``."""
    if subject.kind == "catalog_character":
        return entity_link("character", subject.id)
    if subject.kind == "persona":
        return entity_link("persona", subject.id)
    return format_html("<code>{}</code>", subject.id)


def _scope_name(scope: StoryScope | CatalogScope) -> str:
    return SCOPE_STORY if isinstance(scope, StoryScope) else SCOPE_CATALOG


@dataclass(frozen=True)
class ReferencingRow:
    story_id: str
    story: SafeString
    label: str
    character_ids: list[str]
    erase_links: list[tuple[str, str]]  # (url, text), result page only


def referencing_rows(
    client: EngineClient | None, result: ErasureResult, *, with_links: bool
) -> list[ReferencingRow]:
    """The referencing stories, each linked with its name (``story_labels``); on the result
    page, "Erase character <id[:8]> in <story>" per character id, pre-filling a story-scope
    erasure (not cross-checked against later erasures)."""
    ids = [s.story_id for s in result.referencing_stories]
    labels = story_labels(client, ids) if client is not None and ids else {}
    rows = []
    for ref in result.referencing_stories:
        found = labels.get(ref.story_id)
        text = found.text if found is not None else ref.story_id
        links = []
        if with_links:
            for character_id in ref.character_ids:
                url = erasure.new_url(
                    "character", character_id, scope=SCOPE_STORY, story=ref.story_id
                )
                if url is not None:
                    links.append((url, f"Erase character {character_id[:8]} in {text}"))
        rows.append(
            ReferencingRow(
                ref.story_id,
                entity_link("story", ref.story_id),
                text,
                list(ref.character_ids),
                links,
            )
        )
    return rows


def _sign(request: HttpRequest, subject: SubjectRef, scope: Any, preview: ErasureResult) -> str:
    body = {"subject": subject.to_json(), "scope": scope.to_json()}
    base = {
        "offered": [c.candidate_id for c in preview.candidates],
        "key": new_ulid(),
        "operator": request.user.pk,
        "acting": acting_principal(request),
        "preview": dataclasses.asdict(preview),
    }
    return twostage.sign(TWO_STAGE, subject.id, body, base=base)


def _render_preview(
    request: HttpRequest,
    client: EngineClient | None,
    subject: SubjectRef,
    scope: StoryScope | CatalogScope,
    preview: ErasureResult,
    *,
    token: str | None = None,
    ticked: Sequence[str] = (),
    error_text: str = "",
) -> HttpResponse:
    """The dry run's answer and the one way to erase. ``token`` re-offers a payload as it was
    (its key kept); otherwise a new one is signed unless there is nothing to erase."""
    nothing = preview.nothing
    if token is None and not nothing:
        token = _sign(request, subject, scope, preview)
    scope_name = _scope_name(scope)
    context = {
        "subject": subject,
        "subject_kind": SUBJECT_KINDS.get(subject.kind, subject.kind),
        "subject_link": subject_link(subject),
        "scope_label": SCOPE_LABELS[scope_name],
        "story_link": entity_link("story", scope.story) if isinstance(scope, StoryScope) else None,
        "preview": preview,
        "records": record_rows(preview.records),
        "media_label": MEDIA_LABELS[scope_name],
        "groups": candidate_groups(preview.candidates),
        "referencing": referencing_rows(client, preview, with_links=False),
        "nothing": nothing,
        "nothing_text": NOTHING,
        "nothing_rows": NOTHING_ROWS,
        "token": None if nothing else token,
        "ticked": set(ticked),
        "candidate_field": CANDIDATE_FIELD,
        "form_id": FORM_ID,
        "confirm_url": reverse("erasure:run"),
        "confirm_label": ERASE_LABEL,
        "confirm_text": CONFIRM_TEXT,
        "error_text": error_text,
        "back_url": _new_url(choice_of(subject, scope)),
    }
    return render(request, "console/erasure/preview.html", context)


def _expired(request: HttpRequest) -> HttpResponse:
    messages.error(request, twostage.EXPIRED_TEXT)
    return redirect(_new_url())


@dataclass(frozen=True)
class Signed:
    """A payload read back: what to send, and what the preview offered."""

    subject: SubjectRef
    scope: StoryScope | CatalogScope
    offered: list[str]
    key: str
    preview: ErasureResult | None


def _unsigned(request: HttpRequest) -> Signed | None:
    """The posted payload, or ``None`` when it is missing, expired, tampered with, another
    operator's or made while acting as someone else (all handled alike)."""
    try:
        payload = twostage.unsign(TWO_STAGE, request.POST.get(twostage.CONFIRM_FIELD, ""))
    except twostage.ConfirmationExpired:
        return None
    body = payload.body if isinstance(payload.body, dict) else {}
    base = payload.base if isinstance(payload.base, dict) else {}
    subject = SubjectRef.from_json(body.get("subject"))
    scope = scope_from_json(body.get("scope"))
    offered = base.get("offered")
    key = base.get("key")
    if (
        subject is None
        or scope is None
        or subject.id != payload.target_id
        or not isinstance(offered, list)
        or not all(isinstance(i, str) for i in offered)
        or not isinstance(key, str)
        or base.get("operator") != request.user.pk
        or base.get("acting") != acting_principal(request)
    ):
        return None
    return Signed(subject, scope, offered, key, ErasureResult.from_json(base.get("preview")))


def _dry_run(
    request: HttpRequest,
    client: EngineClient,
    subject: SubjectRef,
    scope: Any,
    choice: Choice | None = None,
) -> HttpResponse:
    """The dry run; a refusal re-renders the form with ``choice`` (the posted values, so a
    catalog scope keeps the story a story character was picked from), else with the values
    the request was built from."""
    choice = choice or choice_of(subject, scope)
    try:
        preview = client.erase(subject, scope, dry_run=True)
    except EngineClientError as exc:
        log_engine_error(request, exc)
        return _place_error(request, client, exc, choice)
    return _render_preview(request, client, subject, scope, preview)


@require_POST
def erasure_preview(request: HttpRequest) -> HttpResponse:
    """The dry run, from the form or ("Preview again") from a signed payload."""
    client = engine_client_for(request)
    if twostage.CONFIRM_FIELD in request.POST:
        signed = _unsigned(request)
        if signed is None:
            return _expired(request)
        return _dry_run(request, client, signed.subject, signed.scope)
    form = ErasureForm(request.POST)
    if not form.is_valid():
        errors = {name: [str(e) for e in found] for name, found in form.errors.items()}
        return _render_form(request, client, form.choice(), errors=errors)
    return _dry_run(request, client, form.subject_ref(), form.scope_ref(), form.choice())


# --- the real run ---------------------------------------------------------------------------------


def _ticked(request: HttpRequest) -> list[str]:
    return list(dict.fromkeys(v.strip() for v in request.POST.getlist(CANDIDATE_FIELD)))


def _render_problem(
    request: HttpRequest,
    signed: Signed,
    *,
    text: str,
    engine_error: ErrorPanel | None = None,
    again: bool = False,
    retry_ticked: Sequence[str] | None = None,
) -> HttpResponse:
    """A run that did not erase (or may have): the reason, and "Preview again" (a new dry run
    from the payload) or "Retry" (the same payload, ticks and key)."""
    context = {
        "subject": signed.subject,
        "subject_kind": SUBJECT_KINDS.get(signed.subject.kind, signed.subject.kind),
        "subject_link": subject_link(signed.subject),
        "scope_label": SCOPE_LABELS[_scope_name(signed.scope)],
        "text": text,
        "engine_error": engine_error,
        "token": request.POST.get(twostage.CONFIRM_FIELD, ""),
        "again": again,
        "again_url": reverse("erasure:preview"),
        "again_label": PREVIEW_AGAIN,
        "retry": retry_ticked is not None,
        "retry_ticked": list(retry_ticked or ()),
        "retry_url": reverse("erasure:run"),
        "retry_label": RETRY_LABEL,
        "candidate_field": CANDIDATE_FIELD,
        "back_url": _new_url(choice_of(signed.subject, signed.scope)),
    }
    return render(request, "console/erasure/problem.html", context)


@require_POST
def erasure_run(request: HttpRequest) -> HttpResponse:
    """The real run: only from the preview's signed payload, with ticked ids among those it
    offered (at most :data:`MAX_CONFIRM`); anything else makes zero Engine calls."""
    signed = _unsigned(request)
    if signed is None:
        return _expired(request)
    ticked = _ticked(request)
    if any(i not in signed.offered for i in ticked):
        return _render_problem(request, signed, text=CANDIDATES_CHANGED, again=True)
    if len(ticked) > MAX_CONFIRM:
        if signed.preview is None:
            return _render_problem(request, signed, text=TOO_MANY_TICKED, again=True)
        token = request.POST.get(twostage.CONFIRM_FIELD, "")
        return _render_preview(
            request,
            None,
            signed.subject,
            signed.scope,
            signed.preview,
            token=token,
            ticked=ticked,
            error_text=TOO_MANY_TICKED,
        )
    client = engine_client_for(request)
    try:
        result = client.erase(
            signed.subject,
            signed.scope,
            dry_run=False,
            confirm_candidates=ticked,
            idempotency_key=signed.key,
        )
    except EngineUnreachable as exc:
        log_engine_error(request, exc)
        return _render_problem(
            request, signed, text=NO_ANSWER, engine_error=panel_for(exc), retry_ticked=ticked
        )
    except EngineError as exc:
        log_engine_error(request, exc)
        if exc.http_status == 404 or exc.code == SCOPE_CODE:
            return _place_error(request, client, exc, choice_of(signed.subject, signed.scope))
        return _render_problem(
            request,
            signed,
            text=CODE_TEXT.get(exc.code, ""),
            engine_error=panel_for(exc),
            again=exc.code in AGAIN_CODES,
        )
    except EngineClientError as exc:
        log_engine_error(request, exc)
        return _render_problem(request, signed, text="", engine_error=panel_for(exc))
    row = _row(client.last_operation_id)
    replayed = " (replayed)" if row is not None and row.replayed else ""
    key = result.idempotency_key or signed.key
    if result.erasure_id is None:
        return _render_result(request, client, result, note=NO_ERASURE_ID)
    messages.success(
        request, f"Erased — key {key}, operation {result.operation_id or '—'}{replayed}"
    )
    return redirect(erasure.result_url(result.erasure_id))


def _row(pk: int | None) -> EngineOperation | None:
    return EngineOperation.objects.filter(pk=pk).first() if pk is not None else None


